import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { exportsOf, packSummary } from './api-lib.mjs';

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const versionFile = readFileSync('src/rise/version.js', 'utf8');
const version = versionFile.match(/VERSION\s*=\s*'([^']+)'/)?.[1] || pkg.version;
const apiVersion = versionFile.match(/API_VERSION\s*=\s*(\d+)/)?.[1] || '1';

/** Map each core export to its source module. */
function coreGroups() {
  const src = readFileSync('src/rise/index.js', 'utf8');
  const groups = [];
  const re = /export\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"]/g;
  let m;
  while ((m = re.exec(src))) {
    const names = m[1]
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
      .map((s) => s.split(/\s+as\s+/).pop().trim());
    groups.push({ from: m[2], names });
  }
  return groups;
}

/** Summaries for packs whose index.js has no JSDoc block describing the pack as a whole. */
const SUMMARY_OVERRIDE = {
  tilemap: 'Tilemap pack: one SpriteBatch per chunk, collision merged along rows, and autotiling.',
};

const lines = [];
lines.push('# API reference');
lines.push('');
lines.push('> Generated by `npm run docs:api`. Do not edit by hand.');
lines.push(`> Version **${version}** · API_VERSION **${apiVersion}** · ${Object.keys(JSON.parse(readFileSync('scripts/api-surface.json', 'utf8')).packs || {}).length} packs.`);
lines.push('');
lines.push('## Core');
lines.push('');
lines.push('Import from `risejs-core`:');
lines.push('');
lines.push('```js');
lines.push("import { createApp, World, Entity, Input } from 'risejs-core';");
lines.push("import 'risejs-core/style.css';");
lines.push('```');
lines.push('');
lines.push('| Module | Exports |');
lines.push('|---|---|');
for (const g of coreGroups()) {
  lines.push(`| \`${g.from.replace('./', '')}\` | ${g.names.map((n) => '`' + n + '`').join(', ')} |`);
}
lines.push('');
lines.push('## Packs');
lines.push('');
lines.push('Each pack is its own entry: `risejs-core/packs/<name>`.');
lines.push('');
lines.push('| Pack | Exports | Summary |');
lines.push('|---|---|---|');

const root = 'src/rise/packs';
for (const name of readdirSync(root).sort()) {
  const file = join(root, name, 'index.js');
  if (!existsSync(file)) continue;
  const names = exportsOf(file);
  const summary = (SUMMARY_OVERRIDE[name] || packSummary(file)).replace(/\|/g, '\\|');
  lines.push(`| [\`${name}\`](../src/rise/packs/${name}/index.js) | ${names.slice(0, 8).map((n) => '`' + n + '`').join(', ')}${names.length > 8 ? ' …' : ''} | ${summary} |`);
}
lines.push('');
lines.push('## Common subpaths');
lines.push('');
lines.push('| Subpath | Target |');
lines.push('|---|---|');
for (const [sub, target] of Object.entries(pkg.exports || {})) {
  if (sub === '.' || sub === './package.json' || sub.includes('*')) continue;
  lines.push(`| \`${sub}\` | \`${target}\` |`);
}
lines.push('');
lines.push('## API check');
lines.push('');
lines.push('```bash');
lines.push('npm run api:check      # fails if an export is removed without increasing API_VERSION');
lines.push('npm run api:surface -- --write   # update the snapshot after adding exports');
lines.push('```');
lines.push('');

writeFileSync('docs/api-reference.md', lines.join('\n'));
console.log(`wrote docs/api-reference.md (${lines.length} lines)`);
